/**
 * A CARD'S KIND — the daemon's one table of what each kind IS (0.97.0):
 * `code` (the default), `design` and `research`; since 0.105.0 also `model`
 * (the 3D-model kind — not an AI-model pin, which is `job.model`) and `deck`
 * (the presentation kind — not the review deck); since 0.114.0 `image` (one or
 * more generated PNG/WebP pictures — the first non-code kind that runs on
 * Codex rather than Claude). Every reader of a kind goes
 * through this module: the prompts that print it and pick a contract
 * (prompts.mjs, which keeps the strings, with the 3D-model and presentation
 * contracts and the shared tail in artifactContracts.mjs), the agent lane
 * that picks a posture,
 * refuses a runtime (workAgentTurnExecution.mjs) and checks the artifact
 * (workAgentTurnOutcome.mjs), and the turn runner that fences the non-code
 * postures (runTurn.mjs and claudePosture.mjs, via turnProfile.mjs).
 *
 * Split out (SOLID F041) because the kind was branched on at five sites — the
 * vocabulary twice in prompts.mjs, the posture and the artifact rule in the
 * agent lane, the posture names again in claude.mjs — so a fourth kind was a
 * coordinated edit whose missed site ran a card under the wrong posture. Now a
 * kind is one entry here, and `agentTaskKinds.test.mjs` proves every entry has
 * a contract, a posture a runtime can declare, and (for a non-code kind) the
 * artifact that proves it delivered.
 *
 * Pure data and pure functions: no imports, no environment, no I/O — prompts
 * imports it, and prompts is strings.
 */

/**
 * The kinds. Per kind:
 *  - `posture`: the turn profile the card runs under (turnProfile.mjs);
 *  - `artifact`: null for code (it delivers commits), else what proves a
 *    delivery — `match` over the artifact file name, and the `missing`
 *    sentence a turn settles `nothing` with when the proof was not written;
 *  - `offRuntime(rt)`: the sentence when the chosen CLI cannot run the posture.
 */
/** The mockup, 3D-model, presentation and write-up kinds run on Claude: the one
 *  CLI that declares their postures (`design`, `research`). */
const CLAUDE_ONLY = 'mockup, 3D model, presentation and write-up cards run on Claude on this machine';
/** The image kind runs on Codex: the one CLI that declares its posture, because
 *  the pictures come from Codex's own image tool on its own login. */
const CODEX_ONLY = 'image cards run on Codex on this machine';

export const AGENT_TASK_KINDS = Object.freeze({
  code: Object.freeze({
    posture: 'build',
    artifact: null,
    offRuntime: (rt) => `this machine cannot run ${rt}`,
  }),
  design: Object.freeze({
    posture: 'design',
    artifact: Object.freeze({
      match: /\.html?$/i,
      missing: 'the turn ended without writing a mockup under .flowviant/artifacts/',
    }),
    offRuntime: () => CLAUDE_ONLY,
  }),
  /**
   * THE 3D-MODEL KIND (0.105.0; one page since 0.107.0): a three.js page that
   * builds the model in code, which the person exports to one .glb in Review.
   * Under the design fence (read the repo, write only `.flowviant/artifacts/**`):
   * a model is a picture of an asset, and committing it is a separate code
   * card a person raises at Accept. Proven by its page alone — the model is
   * IN the page; 0.105.0's second proof (a .gltf/.glb/.obj beside it) went
   * with the files it asked for.
   */
  model: Object.freeze({
    posture: 'design',
    artifact: Object.freeze({
      match: /\.html?$/i,
      missing: 'the turn ended without writing a 3D model page under .flowviant/artifacts/',
    }),
    offRuntime: () => CLAUDE_ONLY,
  }),
  /**
   * THE IMAGE KIND (0.114.0): one or more raster pictures, generated by
   * Codex's own image tool (`image_generation`, the machine's Codex login —
   * no API key) and copied under `.flowviant/artifacts/`. Its own posture,
   * `image`, which ONLY Codex declares (runtimeCodex.mjs): read the repo,
   * write only the artifacts directory, image generation on, no web. Claude
   * Code draws no raster image, so a Claude container is refused before spawn
   * in these words. Proven by one PNG or WebP — the formats the card is told
   * to hand back; a picture drawn some other way (SVG, an HTML page) is not
   * the delivery.
   */
  image: Object.freeze({
    posture: 'image',
    artifact: Object.freeze({
      match: /\.(png|webp)$/i,
      missing: 'the turn ended without writing a PNG or WebP image under .flowviant/artifacts/',
    }),
    offRuntime: () => CODEX_ONLY,
  }),
  /** THE PRESENTATION KIND (0.105.0): one HTML slide deck, under the design fence. */
  deck: Object.freeze({
    posture: 'design',
    artifact: Object.freeze({
      match: /\.html?$/i,
      missing: 'the turn ended without writing a deck under .flowviant/artifacts/',
    }),
    offRuntime: () => CLAUDE_ONLY,
  }),
  research: Object.freeze({
    posture: 'research',
    artifact: Object.freeze({
      match: /\.md$/i,
      missing: 'the turn ended without writing a write-up under .flowviant/artifacts/',
    }),
    offRuntime: () => CLAUDE_ONLY,
  }),
});

const known = (v) => typeof v === 'string' && Object.hasOwn(AGENT_TASK_KINDS, v);

/**
 * A CARD'S KIND, READ THE ONE WAY THE DAEMON READS IT.
 *
 * The server sends the key only for non-code kinds, so ABSENT IS CODE, and an
 * unknown string (a newer server, a typo) degrades to code: the one kind that
 * changes nothing about how a card is PRINTED. Every printing reader — the
 * contract selector, the kickoff, the spec — goes through this, so no two of
 * them can disagree about what an odd value means.
 */
export const agentTaskKindOf = (v) => (known(v) ? v : 'code');

/**
 * …EXCEPT WHERE A TURN IS ABOUT TO SPAWN (2026-09-23). "Unknown degrades to
 * code" is right for every reader that only PRINTS the kind, and wrong for the
 * one that picks a POSTURE: code is the build turn, permissions skipped, so a
 * kind a newer server invented for a card that must not touch the code (a
 * fourth kind, a typo, `Design`) would have run as exactly the turn it exists
 * to prevent. The agent lane asks this first and refuses in words, relaying
 * the word it was handed. Absent, null and empty stay code — that is how a
 * code card arrives.
 *
 * @returns {string|null} the unrecognised value, or null when the kind is one
 *   this daemon runs.
 */
export const unknownAgentTaskKind = (v) =>
  v === undefined || v === null || v === '' || known(v)
    ? null
    : String(v).replace(/[\u0000-\u001f\u007f]/g, '').slice(0, 40);

/** The table entry for a kind value, read the printing way (unknown → code). */
export const agentTaskKind = (v) => AGENT_TASK_KINDS[agentTaskKindOf(v)];

/** The postures only a card's kind selects (every kind's but code's), each
 *  once: the 3D-model and presentation kinds reuse the design posture; the
 *  image kind has its own. */
export const KIND_POSTURES = Object.freeze([
  ...new Set(
    Object.values(AGENT_TASK_KINDS)
      .map((k) => k.posture)
      .filter((p) => p !== 'build')
  ),
]);
